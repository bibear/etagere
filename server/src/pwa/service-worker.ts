// Source of the PWA service worker (`/sw.js`), generated at build time with the list of shell
// files to precache. Strategy:
// - `/api/*` and other origins: not intercepted (the app's own offline cache handles data);
// - page navigations: network first, the cached shell (`/`) when the server is unreachable;
// - other same-origin GETs (bundles, fonts, icons): cache first, then the network (kept).
// Old caches are deleted on activation. Plain JavaScript: it runs in the browser as is.

export function serviceWorkerSource(precache: readonly string[], version: string): string {
  return `/* Étagère service worker — generated by \`npm run build:web\`. */
'use strict';
const CACHE = 'etagere-shell-${version}';
const PRECACHE = ${JSON.stringify(precache, null, 2)};

self.addEventListener('install', (event) => {
  event.waitUntil(
    caches.open(CACHE).then((cache) => cache.addAll(PRECACHE)).then(() => self.skipWaiting()),
  );
});

self.addEventListener('activate', (event) => {
  event.waitUntil(
    caches
      .keys()
      .then((keys) =>
        Promise.all(
          keys
            .filter((key) => key.startsWith('etagere-shell-') && key !== CACHE)
            .map((key) => caches.delete(key)),
        ),
      )
      .then(() => self.clients.claim()),
  );
});

self.addEventListener('fetch', (event) => {
  const request = event.request;
  if (request.method !== 'GET') return;
  const url = new URL(request.url);
  if (url.origin !== self.location.origin) return;
  if (url.pathname === '/api' || url.pathname.startsWith('/api/')) return;

  if (request.mode === 'navigate') {
    event.respondWith(
      fetch(request).catch(() =>
        caches.open(CACHE).then((cache) => cache.match('/')).then(
          (shell) => shell || Response.error(),
        ),
      ),
    );
    return;
  }

  event.respondWith(
    caches.open(CACHE).then((cache) =>
      cache.match(request).then(
        (cached) =>
          cached ||
          fetch(request).then((response) => {
            if (response.ok) cache.put(request, response.clone());
            return response;
          }),
      ),
    ),
  );
});
`;
}
